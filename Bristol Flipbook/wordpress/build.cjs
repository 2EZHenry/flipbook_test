const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const dest = path.join(__dirname, 'bristol-flipbook/assets');
fs.mkdirSync(dest, { recursive: true });
let html = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
html = html.replace('<button id="sourceBtn" class="btn">Google Drive</button>', '<span>Syron</span>');
html = html.replace('https://unpkg.com/page-flip/dist/js/page-flip.browser.js', 'https://unpkg.com/page-flip@2.0.7/dist/js/page-flip.browser.js');
html = html.replace('const pdfUrl = "./DesignCollection2024.pdf";', 'const pdfUrl = null;');
html = html.replace('<script src="drive-loader.js"></script>', '<script>window.BristolFlipbookConfig = __BRISTOL_CONFIG__;</script>\n<script src="__BRISTOL_ASSET_BASE__auto-loader.js"></script>');
html = html.replace('src="page-flip.wav"', 'src="__BRISTOL_ASSET_BASE__page-flip.wav"');
html = html.replace('src="page-layout.js"', 'src="__BRISTOL_ASSET_BASE__page-layout.js"');
html = html.replace('src="lazy-pages.js"', 'src="__BRISTOL_ASSET_BASE__lazy-pages.js?v=0.1.2"');
html = html.replace('src="fullscreen.js"', 'src="__BRISTOL_ASSET_BASE__fullscreen.js?v=0.1.1"');
html = html.replace('src="zoom-pan.js"', 'src="__BRISTOL_ASSET_BASE__zoom-pan.js?v=0.1.4"');
html = html.replace('href="viewer-polish.css"', 'href="__BRISTOL_ASSET_BASE__viewer-polish.css?v=0.1.4"');
html = html.replace('pdfjsLib.getDocument(source)', 'pdfjsLib.getDocument({ ...source, isEvalSupported: false })');
html = html.replace(/\t\t\tasync function init\(\) \{[\s\S]*?(?=\t\t\twindow\.loadFlipbookSource)/, '\t\t\tflipSoundEl.addEventListener("ended", () => { flipSoundState = "idle"; flipSoundEl.currentTime = 0; flipSoundEl.playbackRate = NORMAL_FLIP_PLAYBACK_RATE; });\n\n');
html = html.replace('\t\t\twindow.startFlipbook = () => init().catch(handleLoadError);', '');
fs.writeFileSync(path.join(dest, 'viewer.html'), html);
for (const name of ['page-layout.js', 'page-flip.wav', 'fullscreen.js', 'lazy-pages.js', 'zoom-pan.js', 'viewer-polish.css']) fs.copyFileSync(path.join(root, name), path.join(dest, name));
console.log('Built WordPress viewer assets.');
